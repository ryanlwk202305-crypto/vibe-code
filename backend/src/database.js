import dotenv from "dotenv";
import fs from "node:fs";
import pg from "pg";
import path from "node:path";
import { fileURLToPath } from "node:url";

const { Pool } = pg;
const backendDirectory = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
dotenv.config({ path: path.join(backendDirectory, ".env") });
const connectionString = process.env.DATABASE_URL;
const caCertificatePath = process.env.SUPABASE_DB_CA_CERT;

if (!connectionString) {
  throw new Error("DATABASE_URL is missing. Add your Supabase PostgreSQL connection string to backend/.env.");
}

const pool = new Pool({
  connectionString,
  ssl: caCertificatePath
    ? {
        ca: fs.readFileSync(path.resolve(backendDirectory, caCertificatePath), "utf8"),
        rejectUnauthorized: true
      }
    : { rejectUnauthorized: false }
});

pool.on("error", () => {
  console.error("Unexpected error from the Supabase PostgreSQL connection pool");
});

export async function initializeDatabase() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS public."Product" (
      pid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      pname TEXT NOT NULL,
      description TEXT NOT NULL DEFAULT '',
      price NUMERIC(10, 2) NOT NULL CHECK (price >= 0),
      qty INTEGER NOT NULL CHECK (qty >= 0)
    );

    CREATE TABLE IF NOT EXISTS public."User" (
      uid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      uname TEXT NOT NULL,
      email TEXT NOT NULL UNIQUE,
      password TEXT NOT NULL
    );

    CREATE TABLE IF NOT EXISTS public."Order" (
      oid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      uid BIGINT NOT NULL REFERENCES public."User"(uid) ON DELETE RESTRICT,
      pid BIGINT NOT NULL REFERENCES public."Product"(pid) ON DELETE RESTRICT,
      order_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
    );
  `);
  await pool.query("SELECT 1");
}

export async function all(sql, parameters = []) {
  const result = await pool.query(sql, parameters);
  return result.rows;
}

export async function one(sql, parameters = []) {
  const result = await pool.query(sql, parameters);
  return result.rows[0] ?? null;
}

export async function run(sql, parameters = []) {
  const result = await pool.query(sql, parameters);
  return { changes: result.rowCount };
}
